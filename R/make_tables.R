                  Cc_S4 = "C: composite, $\\mathbf w^\\star$(S4)")
cfg_label <- c(config_labels, null_labels)
with_se <- function(x, se, d = 0) ifelse(is.na(se), fmt(x, d), paste0(fmt(x, d), " (", fmt(se, 1), ")"))

emit <- function(name, header, rows, footer = "\\bottomrule\n\\end{tabular}") {
  txt <- c("%% Generated by R/make_tables.R from results/*.csv; do not edit by hand.",
           header, rows, footer)
  writeLines(txt, file.path(tab_dir, paste0(name, ".tex")))
  cat("wrote", file.path("manuscript/tables", paste0(name, ".tex")), "\n")
}
row <- function(...) paste(paste(..., sep = " & "), "\\\\")
first_only <- function(x) ifelse(duplicated(x), "", x)

