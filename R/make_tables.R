## =============================================================================
## Writes the LaTeX tables of the manuscript from results/*.csv, so that every
## number in a table is the number the simulation produced.
##
##   Rscript R/make_tables.R        ->  manuscript/tables/*.tex
##
## Each file holds a complete tabular environment (booktabs); body.tex supplies
## the table environment, caption and label. Base R only.
## =============================================================================

here <- local({
  f <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
  if (length(f)) dirname(normalizePath(f)) else "R"
})
root <- dirname(here)
source(file.path(here, "bscme_methods.R"))
source(file.path(here, "scenarios.R"))
res_dir <- file.path(root, "results")
tab_dir <- file.path(root, "manuscript", "tables")
dir.create(tab_dir, recursive = TRUE, showWarnings = FALSE)

rd  <- function(f) read.csv(file.path(res_dir, f), stringsAsFactors = FALSE)
fmt <- function(x, d = 2) ifelse(is.na(x), "--", formatC(x, format = "f", digits = d))
fmt_n1 <- function(x) ifelse(is.finite(x), formatC(round(x), format = "d"), paste0("$>$", max(n1_grid)))
fmt_ratio <- function(s) {                      # "0.42", "<0.34", ">3.01" or NA
  s <- as.character(s)
  ifelse(is.na(s) | s == "", "", gsub("^([<>])", "$\\1$", s))
}
fmt_theta <- function(x) ifelse(x < 0, sprintf("$%.2f$", x), sprintf("%.2f", x))
design_label <- c(M = "M: co-primary gate",
                  Cu = "C: composite, uniform $\\mathbf w$",
