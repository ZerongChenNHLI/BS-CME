wide <- function(d, vars, digits) {
  key <- unique(d[, c("cfg", "design")])
  key <- key[order(match(key$cfg, names(cfg_label)), match(key$design, names(design_label))), ]
  cells <- t(apply(key, 1, function(k) {
    unlist(lapply(rho_latent, function(r) {
      z <- d[d$cfg == k[["cfg"]] & d$design == k[["design"]] & d$rho == r, ]
      mapply(function(v, dg) fmt(z[[v]], dg), vars, digits)
    }))
  }))
  list(key = key, cells = cells)
}
wa <- wide(alt, c("pcs", "power", "EN"), c(2, 2, 0))
rows <- unlist(lapply(unique(wa$key$cfg), function(s) {
  i <- which(wa$key$cfg == s)
